const I18n = (() => {
  const STORAGE_KEY = 'healthify_lang';

  const DEFAULT_LANG = 'es';

  let currentLang = DEFAULT_LANG;

  function getLang() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      return translations[saved] ? saved : DEFAULT_LANG;
    } catch (_) {
      return DEFAULT_LANG;
    }
  }

  function setLang(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (_) {}
    applyTranslations();
    updateLangSelects();
    applyLangAttributes();
    document.dispatchEvent(new CustomEvent('i18n:change', { detail: { lang } }));
  }

  function applyLangAttributes() {
    document.documentElement.lang = currentLang === 'es' ? 'es-419' : 'en-US';
  }

  function t(key) {
    return (translations[currentLang] && translations[currentLang][key]) ||
           (translations[DEFAULT_LANG] && translations[DEFAULT_LANG][key]) ||
           key;
  }

  function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const val = t(el.getAttribute('data-i18n'));
      if (el.hasAttribute('data-i18n-html')) {
        el.innerHTML = val;
      } else {
        el.textContent = val;
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    });

    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });

    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
      el.setAttribute('alt', t(el.getAttribute('data-i18n-alt')));
    });

    document.querySelectorAll('img[data-i18n-img]').forEach(img => {
      if (!img.dataset.srcBase) img.dataset.srcBase = img.getAttribute('src');
      const base = img.dataset.srcBase;
      const src = currentLang === DEFAULT_LANG ? base : base.replace(/[^/]+$/, `${currentLang}/$&`);
      if (img.getAttribute('src') === src) return;
      img.onerror = () => { img.onerror = null; img.src = base; };
      img.src = src;
    });
  }

  function updateLangSelects() {
    document.querySelectorAll('.lang-select').forEach(sel => {
      sel.value = currentLang;
    });
  }

  function init() {
    currentLang = getLang();
    applyTranslations();
    updateLangSelects();
    applyLangAttributes();

    document.querySelectorAll('.lang-select').forEach(sel => {
      sel.addEventListener('change', e => setLang(e.target.value));
    });
  }

  return { init, setLang, t, getLang: () => currentLang };
})();
